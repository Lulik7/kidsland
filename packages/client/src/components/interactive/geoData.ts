/** The Georgian alphabet (Mkhedruli): the letter, its sound in Russian letters and a word to remember it by. */
export interface GeoLetter {
  ch: string;
  ru: string;
  word: string;
  wordRu: string;
  pic: string;
}

const row = (list: [string, string, string, string, string][]): GeoLetter[] =>
  list.map(([ch, ru, word, wordRu, pic]) => ({ ch, ru, word, wordRu, pic }));

