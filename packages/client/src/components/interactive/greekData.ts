/** The Greek alphabet: capital and small letter, the letter's name, its sound in Russian letters and a word to remember it by. */
export interface GreekLetter {
  cap: string;
  ch: string;
  name: string;
  ru: string;
  word: string;
  wordRu: string;
  pic: string;
}

const row = (list: [string, string, string, string, string, string, string][]): GreekLetter[] =>
  list.map(([cap, ch, name, ru, word, wordRu, pic]) => ({ cap, ch, name, ru, word, wordRu, pic }));

