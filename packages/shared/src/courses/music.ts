/** Puts the right answer at a position that depends on the question id, so it is not always first. */
function place(id: string, right: string, wrong: string[]): { options: string[]; answer: number } {
  const pos = [...id].reduce((a, ch) => a + ch.charCodeAt(0), 0) % (wrong.length + 1);
  const options = [...wrong];
  options.splice(pos, 0, right);
  return { options, answer: pos };
}

const single = (id: string, prompt: string, right: string, wrong: string[], explain?: string): Question => ({
  id,
  kind: 'single',
  prompt,
  ...place(id, right, wrong),
  ...(explain ? { explain } : {}),
});

const fromFact = (id: string, f: Fact) => single(id, f.prompt, f.right, f.wrong);

