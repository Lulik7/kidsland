import type { Course, Question } from './types';

/** Single-answer question with the right option at position `at`. */
function single(id: string, prompt: string, right: string, wrong: [string, string], at = 0): Question {
  const options = [...wrong];
  options.splice(at, 0, right);
  return { id, kind: 'single', prompt, options, answer: at };
}

